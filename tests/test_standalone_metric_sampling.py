"""Sampling-boundary checks for the independent SA/PC source packages.

No model, decoder, checkpoint or GPU is loaded. NumPy is the repository's
existing development dependency and supplies the original scalar rounding.
"""

import importlib.util
from pathlib import Path
import sys
import unittest


ROOT = Path(__file__).resolve().parents[1] / "metric_packages"
PACKAGES = ("01_semantic_adherence", "02_physical_commonsense")


def load_sampler(package):
    name = "standalone_sampling_" + package
    path = ROOT / package / "modified" / "sapc" / "sampling.py"
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module  # dataclass resolves annotations via the module.
    try:
        # Keep these source packages free of generated bytecode artifacts.
        exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), module.__dict__)
    finally:
        sys.modules.pop(name, None)
    return module


class StandaloneMetricSamplingTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.samplers = {package: load_sampler(package) for package in PACKAGES}

    def test_official_fixed_32_segment_centers(self):
        # Unlike uniform endpoint sampling, the 65-frame official case uses
        # odd indices 1..63. A one-frame clip repeats its only frame 32 times.
        for package, sampler in self.samplers.items():
            for count, expected in ((1, [0] * 32), (33, list(range(32))),
                                    (65, list(range(1, 64, 2)))):
                with self.subTest(package=package, source_frames=count):
                    plan = sampler.make_plan(count, 24, family="videophy")
                    self.assertEqual(plan.indices, expected)
                    self.assertEqual(plan.to_dict()["sampled_frames"], 32)
                    self.assertIsNone(plan.frame_cap)

    def test_short_half_sampling_uses_official_floor(self):
        for package, sampler in self.samplers.items():
            for count in (1, 2, 31, 32, 33, 61, 62):
                with self.subTest(package=package, source_frames=count):
                    official = sampler.make_plan(count, 24, family="videophy")
                    half = sampler.make_plan(count, 24, family="videophy",
                                             mode="half", frame_cap=256)
                    self.assertEqual(half.indices, official.indices)
                    self.assertTrue(half.sampling_floor_applied)
                    self.assertFalse(half.sampling_cap_applied)
                    self.assertEqual(len(half.indices), 32)
                    self.assertEqual(half.uncapped_sampled_frames, (count + 1) // 2)

    def test_half_stride_boundary_and_cap_threshold(self):
        for package, sampler in self.samplers.items():
            for count in (63, 64, 65, 511, 512):
                with self.subTest(package=package, source_frames=count):
                    half = sampler.make_plan(count, 24, family="videophy",
                                             mode="half", frame_cap=256)
                    self.assertEqual(half.indices, list(range(0, count, 2)))
                    self.assertFalse(half.sampling_floor_applied)
                    self.assertFalse(half.sampling_cap_applied)
                    self.assertEqual(half.to_dict()["source_frame_stride"], 2)
                    # At 512 frames, the uncapped stride ends at 510, not 511.
                    # The endpoint is added only when whole-clip capping applies.
                    self.assertEqual(len(half.indices), (count + 1) // 2)

    def test_capped_half_sampling_covers_whole_video(self):
        for package, sampler in self.samplers.items():
            for count in (513, 1001, 4097):
                with self.subTest(package=package, source_frames=count):
                    plan = sampler.make_plan(count, 24, family="videophy",
                                             mode="half", frame_cap=256)
                    self.assertEqual(len(plan.indices), 256)
                    self.assertEqual(len(set(plan.indices)), 256)
                    self.assertEqual(plan.indices[0], 0)
                    self.assertEqual(plan.indices[-1], count - 1)
                    self.assertTrue(plan.sampling_cap_applied)
                    self.assertFalse(plan.sampling_floor_applied)
                    self.assertIsNone(plan.to_dict()["source_frame_stride"])
                    if count == 513:
                        self.assertEqual(plan.indices[127:129], [254, 257])
                        self.assertEqual(plan.indices[-4:], [505, 507, 509, 512])

    def test_mr_family_is_not_included(self):
        for package, sampler in self.samplers.items():
            with self.subTest(package=package):
                self.assertFalse(hasattr(sampler, "mr_context_budget"))
                with self.assertRaises(ValueError):
                    sampler.make_plan(65, 24, family="mr")


if __name__ == "__main__":
    unittest.main()
